def get_nwchem_calculator(
    task,
    nwchem_command,
    mult,
    memory_per_core=2000,
    basis="def2-svp",
    xc="xpbe96 1.0 xcampbe96 -0.25 cpbe96 1.0 srhfexch 0.25",
    cam=None,
    solvent=None,
    dft_settings=None,
    driver_settings=None,
    **kwargs,
):
    """
    Returns a NWChem calculator with the specified settings.
    # basis must be adjusted for all species present
    task:str
        The task to be performed by NWChem, e.g., "energy", "TDDFT energy", "optimize", etc.
    nwchem_command:str
        The command to run NWChem, typically generated by `get_nwchem_command`.
    mult:int
        The multiplicity of the system (1 for singlet, 2 for doublet, etc.).
    memory_per_core:int
        The amount of memory allocated per core in megabytes.
    basis:
        Basis set passed to ASE's NWChem calculator.
    xc:
        Exchange-correlation setting passed in the DFT block.
    cam:
        Optional CAM parameters for range-separated/hybrid functionals.
        Leave unset for functionals such as PBE0 that only need the DFT
        ``xc`` keyword.
    solvent:
        Optional COSMO solvent name. ``None``/empty/gas-phase values are
        omitted; otherwise ASE renders this as a NWChem ``cosmo`` block.
    dft_settings:
        Additional values merged into the DFT block.
    driver_settings:
        Additional values merged into the driver block.
    **kwargs:
        Additional keyword arguments to pass to the NWChem calculator.
    """
    from ase.calculators.nwchem import NWChem

    dft_block = dict(
        xc=xc,
        mult=mult,
        iterations="800",
        grid="fine",
        convergence=dict(
            rabuck=20,  # the defaults for convergence improvements
            lshift=0,
            ncydp="0",
            dampon="1d99",
            dampoff="1d-4",
            damp=40,
        ),
    )
    if cam:
        dft_block["cam"] = cam
    if dft_settings:
        dft_block.update(dict(dft_settings))

    driver_block = {"maxiter": 200, "trust": 0.5, "gmax": 0.00036, "grms": 0.00030}
    if driver_settings:
        driver_block.update(dict(driver_settings))

    cosmo_block = dict(kwargs.pop("cosmo", {}) or {})
    normalized_solvent = normalize_nwchem_solvent(solvent)
    if normalized_solvent is not None:
        cosmo_block["solvent"] = normalized_solvent
    if cosmo_block:
        kwargs["cosmo"] = cosmo_block

    return NWChem(
        command=nwchem_command,
        memory=f"total {memory_per_core} mb",
        basis={"*": basis},
        dft=dft_block,
        driver=driver_block,
        task=task,
        restart_kw="start",
        **kwargs,
    )


def apply_default_basis(atoms):
    """
    Applies the default basis set to the atoms in the calculator.
    This is a placeholder function; actual implementation may vary.
    """
    assert (
        atoms.calc is not None
    ), "Calculator must be set before applying the default basis."
    assert (
        atoms.calc.__class__.__name__ == "NWChem"
    ), "Calculator must be an instance of NWChem."

    ecp_defaults = {
        "Au": "library lanl2dz_ecp",
        "Cu": "library lanl2dz_ecp",
        "Ag": "library lanl2dz_ecp",
    }
    basis_defaults = {
        "C": "6-31G**",
        "H": "6-31G**",
        "O": "6-31G**",
        "Au": "lanl2dz_ecp",
        "Cu": "lanl2dz_ecp",
        "Ag": "lanl2dz_ecp",
    }

    atoms.calc.parameters["basis"] = {
        atom.symbol: basis_defaults.get(atom.symbol, "default") for atom in atoms
    }
    # If any of the atoms in the system are in the ECP defaults, add them to the parameters
    if len(set(atoms.get_chemical_symbols()).intersection(ecp_defaults)):
        atoms.calc.parameters["ecp"] = {
            atom.symbol: ecp_defaults[atom.symbol]
            for atom in atoms
            if atom.symbol in ecp_defaults
        }



def get_nwchem_socket_calculator(
    calc,
    type="ipi",
    logfile="socket.io",
    socketname="nwchem",
    check_socket=True,
    verbose=False,
    codata_warning=True,
    host="127.0.0.1",
    port=None,
):
    """
    Returns a NWChem calculator that uses sockets for communication with ASE.
    Parameters:
        port: None or Integer
            The port for connection between FHI-aims and ASE with i-Pi sockets.
            This is fairly arbitrary as long as it doesn't clash with local settings.
            If None an integer between 12345 and 60000 will be picked at random.
        type: String
            Type of socket connection. Default is 'IPI' for i-Pi compatibility. Alternative is UNIX
        host: String
            Name of host computer for ASE. Necessary for calculations where MPI runs on the compute nodes.
            This is now defaulted to None, and then will self-identify the host name if unidentified.
            Long-term, we should consider removing this variable to insulate the users from having to set it.
        logfile: String
            Location of output from sockets communication.
        socketname: String
            Name of the unix socket file for the calculator. Critical for ensuring no clashes occur.
            f"/tmp/ipi-{socketname}.log"
        check_socket: Boolean
            Whether we want the automatically identify and resolve port clashes.
        verbose: Boolean
            For testing of the interface when searching for empty ports.
        codata_warning: Boolean
            Warn the user about Hartree to eV conversion being performed in ASE rather than FHI-aims.
            ASE uses CODATA 2014 and FHI-aims uses CODATA 2002 which yields energy discrepancies.
            The warning message can be turned off if set to False.

    ############## TODO: THE SOCKETS DO NOT WORK WITH TASK-FARMING ###############
    
    """
    # Setup sockets calculator that "wraps" the default calculator
    from ase.calculators.socketio import SocketIOCalculator

    if host is None:
        # On machines where ASE and QM code are run separately (e.g. ASE on login node, QM on compute nodes)
        # we need to specifically state what the name of the login node is so the two packages can communicate
        # In order to manage this communication in all situations, here we will find and use the hostname *even*
        # if on the same computer (it should work irrespective)
        host = socket.gethostname()

    # Random port assignment
    if port:
        pass
    else:
        import random

        port = random.randint(12345, 60000)

    if check_socket:
        port = _check_socket(host, port, verbose)

    if type.lower() == "ipi":
        # Add in SOCKET parameter with host and port details to get sockets working
        calc.parameters.driver["SOCKET"] = f"IPI_CLIENT {host}:{port} RETRIES 100 DELAY 5"
        socket_calc = SocketIOCalculator(calc, log=logfile, port=port)
    elif type.lower() == "unix":
        socket_calc = SocketIOCalculator(calc, log=logfile, unixsocket=socketname)
        calc.parameters.driver["SOCKET"] = f"UNIX {socketname}"

    if codata_warning:
        print("You are using i-Pi based socket connectivity between ASE and a QM code.")
        print("The communicated energy in Hartree units will be converted to eV in ASE and not FHI-aims.")
        print("ASE converts Hartrees to eV (CODATA 2014) and outputs that.")
        print("Definition of the constants in each CODATA version can be found at https://wiki.fysik.dtu.dk/ase/_modules/ase/units.html in CODATA{} and create_units().")
        print("PLEASE BE CONSISTENT IN THE UNIT CONVERSION FOR DATA ANALYSIS!")
        print("You can turn off this message by setting 'codata_warning' keyword to False.")

    return socket_calc, calc


def _check_socket(host, port, verbose=False):
    """
    Function to check if a port is open on the target machine.

    Args:
        host: string
            Name of the host machine on which the port is being tested.
        port: integer
            Starting port value for testing
        verbose: Boolean
            Whether to output the process of the check on all ports.

    Returns:
        Integer: Port number as received (if port is open) or updated (if port is closed)
    """
    import socket
    from contextlib import closing

    with closing(socket.socket(socket.AF_INET, socket.SOCK_STREAM)) as sock:
        # Check if socket is open. If so, it's unsuitable for use so the port number is updated.
        # Repeat until we find a port number that is not in use currently.
        while not sock.connect_ex((host, port)):
            # Debug statement
            if verbose:
                print("Port #" + str(port - 1) + " is unavailable.")
            # Update port
            port += 1
            # Raise issue if port number gets to big!
            if port > 65534:
                raise Exception("No available ports found")
    # Debug statement
    if verbose:
        print("Port #" + str(port) + " is available.")

    return port
