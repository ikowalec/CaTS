def normalize_nwchem_solvent(solvent):
    if solvent is None:
        return None
    text = str(solvent).strip()
    if not text:
        return None
    lowered = text.lower()
    if lowered in {"none", "off", "gas", "gas-phase", "gas_phase", "vacuum"}:
        return None
    if lowered.startswith("solvent "):
        text = text.split(None, 1)[1].strip()
        lowered = text.lower()
    if "(" in text and text.endswith(")"):
        text = text[text.find("(") + 1 : -1].strip()
        lowered = text.lower()
    return {"water": "h2o"}.get(lowered, lowered)


def get_nwchem_path(hpc):
    """Parameterize the NWChem path based on the HPC environment."""
    hpc_dict = {
        "falcon": os.environ.get(
            "NWCHEM_EXECUTABLE",
            "/shared/home2/app_shared/PROJECT/nwchem-7.2.2/bin/nwchem",
        ),
    }

    return hpc_dict[hpc] if hpc in hpc_dict else None


def get_nwchem_command(hpc, nodes, cores_per_node, cores):
    """
    Returns the NWChem command string for running the calculation.
    """
    # Construct the NWChem command
    hpc_key = str(hpc or "").strip().lower()
    nwchem_path = get_nwchem_path(hpc_key)

    def get_nwchem_preamble(hpc):
        """
        Returns the preamble for the NWChem command based on the HPC environment.
        TODO: Expand this function to include more HPC environments.
        """
        preamble_dict = {
            "falcon": "time mpirun",
        }

        return preamble_dict.get(hpc, None)

    if hpc_key == "falcon":
        mpi_ranks = int(os.environ.get("NWCHEM_MPI_RANKS") or 0)
        if mpi_ranks <= 0:
            mpi_ranks = int(cores)
        return f"{get_nwchem_preamble(hpc_key)} -np {mpi_ranks} {nwchem_path} PREFIX.nwi > PREFIX.nwo 2>&1"

    nwchem_command = f"{get_nwchem_preamble(hpc_key)} --nodes={nodes} --ntasks={cores} {nwchem_path} PREFIX.nwi > PREFIX.nwo 2>&1"

    return nwchem_command


